import { UrlSource } from '../services/UrlAnalysisService';

export interface UrlMetadata {
  title?: string;
  description?: string;
  /** S3 key（上傳後的預覽圖） */
  image?: string;
  /** 裝置端提供的原始預覽圖網址，背景處理時下載並上傳 S3 */
  imageSourceUrl?: string;
  source?: UrlSource;
  tags?: string[];
}

/* pending：已存入、metadata 背景處理中；ready：處理完成；failed：重試後仍失敗 */
export type UrlStatus = 'pending' | 'ready' | 'failed';

export class Url {
  constructor(
    public readonly id: string,
    public readonly url: string,
    public readonly metadata: UrlMetadata,
    public readonly createdAt: Date,
    /* null 代表尚未遷移的舊資料 */
    public readonly ownerEmail: string | null = null,
    /* 舊資料沒有此欄位，視為 ready */
    public readonly status: UrlStatus = 'ready'
  ) {
    this.validateUrl(url);
  }

  private validateUrl(url: string): void {
    if (!url || url.trim().length === 0) {
      throw new Error('URL cannot be empty');
    }

    let protocol: string;
    try {
      protocol = new URL(url).protocol;
    } catch {
      throw new Error('Invalid URL format');
    }

    // 連結會被前端渲染成 <a href>，擋掉 javascript: 等 scheme
    if (protocol !== 'http:' && protocol !== 'https:') {
      throw new Error('Invalid URL protocol: only http and https are supported');
    }
  }

  static create(
    url: string,
    metadata: UrlMetadata = {},
    ownerEmail: string | null = null,
    status: UrlStatus = 'ready'
  ): Url {
    return new Url(
      '', // ID will be generated by repository
      url,
      metadata,
      new Date(),
      ownerEmail,
      status
    );
  }

  updateMetadata(metadata: UrlMetadata): Url {
    return new Url(
      this.id,
      this.url,
      { ...this.metadata, ...metadata },
      this.createdAt,
      this.ownerEmail,
      this.status
    );
  }

  withStatus(status: UrlStatus): Url {
    return new Url(this.id, this.url, this.metadata, this.createdAt, this.ownerEmail, status);
  }

  addTag(tag: string): Url {
    const currentTags = this.metadata.tags || [];
    if (!currentTags.includes(tag)) {
      const updatedMetadata = {
        ...this.metadata,
        tags: [...currentTags, tag]
      };
      return this.updateMetadata(updatedMetadata);
    }
    return this;
  }

  removeTag(tag: string): Url {
    const currentTags = this.metadata.tags || [];
    const updatedTags = currentTags.filter(t => t !== tag);
    const updatedMetadata = {
      ...this.metadata,
      tags: updatedTags
    };
    return this.updateMetadata(updatedMetadata);
  }
} 